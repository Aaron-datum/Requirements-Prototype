import { expect, test, type Page } from '@playwright/test'
import { DENSITIES, noHorizontalOverflow, setPrefs, THEMES, trackErrors } from './helpers'

const runSearch = async (page: Page) => {
  await page.goto('/create/bom/03-review')
  await expect(page.getByTestId('presearch-banner')).toBeVisible()
  await page.getByRole('button', { name: 'Run Surrogate Search' }).first().click()
  await expect(page.getByTestId('search-progress')).toBeVisible()
  await expect(page.getByTestId('bom-review')).toHaveAttribute('data-search', 'done', { timeout: 15_000 })
}
const legend = (page: Page, tier: string) => page.getByTestId('cert-legend').locator(`[data-tier="${tier}"] b`)

test.describe('Phase 5: BOM creation and cost', () => {
  test('/create/bom redirects to the current step and the stepper is clickable', async ({ page }) => {
    await page.goto('/create/bom')
    await expect(page).toHaveURL(/\/create\/bom\/01-intake/)
    await expect(page.getByTestId('pipeline-stepper').locator('a')).toHaveCount(7)
    await page.getByTestId('pipeline-stepper').getByText('Assembly tree').click()
    await expect(page).toHaveURL(/02-tree/)
    await page.goto('/create/bom')
    await expect(page).toHaveURL(/02-tree/)
    await expect(page.getByTestId('pipeline-stepper').locator('a[data-step="05-mapping"]')).toHaveAttribute('href', '/create/requirements/05-mapping')
  })

  test('01 intake: tracks, sources, route pills recompute counts, template columns', async ({ page }) => {
    const errs = trackErrors(page)
    await page.goto('/create/bom/01-intake')
    await expect(page.getByRole('heading', { name: 'RFQ package received' })).toBeVisible()
    await expect(page.getByTestId('cad-subs')).toHaveText('9')
    await expect(page.getByTestId('req-extracted')).toHaveText('244')
    await expect(page.getByTestId('req-inscope')).toHaveText('98')
    await expect(page.getByTestId('package-table').locator('tr[data-file]')).toHaveCount(8)
    await expect(page.getByTestId('template-columns')).toContainText('21 = 13 matched + 5 to confirm + 3 custom')
    // cycling the SOR route: Requirements -> Columns
    await page.locator('tr[data-file="f-sor"] button').click()
    await expect(page.getByTestId('req-extracted')).toHaveText('96')
    await expect(page.getByTestId('docs-count')).toHaveText('2')
    await expect(page.getByTestId('sub-01-intake')).toContainText('2 to requirements')
    // Upload and Link are inert
    await expect(page.getByRole('button', { name: 'Upload Files' })).toBeDisabled()
    // disconnecting SAP relabels quotes downstream
    await page.locator('[data-source="sap"]').getByRole('button', { name: 'Manage' }).click()
    await page.getByRole('button', { name: 'Disconnect' }).click()
    await expect(page.locator('[data-source="sap"]')).toContainText('Not connected')
    await page.getByRole('link', { name: /Review Assembly Tree/ }).click()
    await expect(page).toHaveURL(/02-tree/)
    expect(errs).toEqual([])
  })

  test('02 assembly tree: footer summary, reference include, manual line, CAD upload flips to Has CAD', async ({ page }) => {
    await page.goto('/create/bom/02-tree')
    await expect(page.getByTestId('tree-footer')).toHaveText('lines from 58 parts')
    await expect(page.getByTestId('tree-lines')).toHaveText('56')
    await page.locator('[data-row="REF-ENV-01"]').getByRole('button', { name: 'Include' }).click()
    await expect(page.getByTestId('tree-lines')).toHaveText('57')
    await expect(page.locator('[data-row="REF-ENV-01"] [data-cad="none"]')).toBeVisible()
    await page.locator('[data-row="REF-ENV-01"]').getByRole('button', { name: /upload CAD/ }).click()
    await expect(page.locator('[data-row="REF-ENV-01"] [data-cad="has"]')).toBeVisible()
    await expect(page.getByText('CAD attached: Envelope reference body')).toBeVisible()
    await page.getByRole('button', { name: 'Add Manual Line' }).click()
    await page.getByLabel('Part name').fill('Bracket test')
    await page.getByRole('button', { name: 'Add line' }).click()
    await expect(page.getByTestId('tree-lines')).toHaveText('58')
    await expect(page.getByTestId('sub-02-tree')).toContainText('of 59 parts selected')
    await page.locator('[data-row="BOML-0111"]').getByRole('checkbox').uncheck({ force: true })
    await expect(page.getByTestId('tree-lines')).toHaveText('57')
  })

  test('03 BOM review: Si BOM, 56 lines, certainty spread, derived KPIs, retry the simulated failure', async ({ page }) => {
    const errs = trackErrors(page)
    await runSearch(page)
    await expect(page.getByTestId('line-count')).toHaveText('56 lines')
    // first search: one simulated failure (docs/04: per-session Search failed line with retry)
    await expect(legend(page, 'Actual')).toHaveText('40')
    await expect(legend(page, 'Surrogate')).toHaveText('13')
    await expect(legend(page, 'Estimated')).toHaveText('1')
    await expect(legend(page, 'No match')).toHaveText('1')
    await expect(legend(page, 'Search failed')).toHaveText('1')
    await expect(page.getByTestId('kpi-cost')).toContainText('$')
    await expect(page.getByTestId('kpi-reuse')).toHaveText('95%')
    await expect(page.locator('[data-testid="kpis"]')).toContainText('55 of 56 lines priced')
    await expect(page.getByTestId('counter-confirmed')).toContainText('0 of 13')
    await expect(page.getByTestId('counter-unresolved')).toContainText('3')
    // grouped table with certainty chips from the vocabulary
    await expect(page.locator('tr[data-row-id]').first()).toBeVisible()
    await expect(page.getByText('Turbocharger System').first()).toBeVisible()
    await page.getByRole('button', { name: 'Retry' }).first().click()
    await expect(page.getByTestId('kpis')).toContainText('56 of 56 lines priced', { timeout: 10_000 })
    await expect(legend(page, 'Actual')).toHaveText('41')
    await expect(page.getByTestId('kpi-cost')).toHaveText('$4,071.36')
    expect(errs).toEqual([])
  })

  test('03 BOM review: panel tabs, accept as surrogate writes an audit entry', async ({ page }) => {
    await runSearch(page)
    await page.locator('tr[data-row-id="BOML-0153"]').click()
    await expect(page).toHaveURL(/line=BOML-0153/)
    const panel = page.getByTestId('side-panel')
    for (const t of ['Summary', 'Similarity', 'Costing', 'PLM']) await expect(panel.getByRole('tab', { name: t })).toBeVisible()
    await expect(panel.getByTestId('agent-gate')).toContainText('Propose')
    await panel.getByRole('tab', { name: 'Similarity' }).click()
    await expect(page).toHaveURL(/tab=similarity/)
    await expect(panel.getByTestId('similar-to')).toContainText('95%')
    await expect(panel.getByTestId('breakdown').getByRole('meter')).toHaveCount(5)
    await panel.getByRole('button', { name: 'Accept as surrogate' }).click()
    await expect(panel.getByText('Confirmed surrogate').first()).toBeVisible()
    await expect(panel.getByTestId('audit-entry').first()).toContainText('Accepted surrogate')
    await expect(panel.getByTestId('audit-entry').first()).toContainText('Aaron Keller')
    await expect(page.getByTestId('counter-confirmed')).toContainText('1 of 13')
    // Costing, PLM
    await panel.getByRole('tab', { name: 'Costing' }).click()
    await expect(panel.getByTestId('line-price')).toContainText('$32.88')
    await expect(panel.getByRole('button', { name: 'Change suppliers' })).toBeDisabled()
    await panel.getByRole('tab', { name: 'PLM' }).click()
    await expect(panel.getByRole('button', { name: 'Open in PLM' })).toBeDisabled()
    // state by line type
    await page.locator('tr[data-row-id="BOML-0164"]').click()
    await panel.getByRole('tab', { name: 'Similarity' }).click()
    await expect(panel).toContainText('Estimated · cost model')
    await expect(panel.getByRole('button', { name: 'Request quote' })).toBeDisabled()
    await page.locator('tr[data-row-id="BOML-0166"]').click()
    await panel.getByRole('tab', { name: 'Similarity' }).click()
    await expect(panel.getByTestId('unresolved')).toContainText('Loosen the search')
    await panel.getByRole('button', { name: 'Match manually' }).click()
    await expect(panel.getByTestId('match-manually')).toContainText('Provenance: manual')
    await page.locator('tr[data-row-id="BOML-0111"]').click()
    await panel.getByRole('tab', { name: 'Similarity' }).click()
    await expect(panel).toContainText('Carryover — geometric duplicate')
  })

  test('flow 4: Search on opens a new tab; a decision there updates the line and audit here', async ({ page, context }) => {
    await runSearch(page)
    await page.locator('tr[data-row-id="BOML-0166"]').click()
    await expect(page.getByTestId('counter-unresolved')).toContainText('3')
    const link = page.getByTestId('search-on-BOML-0166')
    await expect(link).toHaveAttribute('target', '_blank')
    const href = (await link.getAttribute('href'))!
    expect(href).toMatch(/^\/search\/define\?file=[^&]+&modality=part-to-part&rep=ELEC-925-C&ctx=bom-review%3ABOML-0166&ret=/)
    // Real round trip: the second tab runs the search and applies the decision through the shared ledger.
    const second = await context.newPage()
    await second.goto(href)
    await expect(second.getByTestId('represents')).toContainText('ELEC-925-C')
    await second.getByRole('button', { name: 'Run Search' }).click()
    await second.getByRole('button', { name: 'Select as surrogate' }).first().click()
    await expect(second).toHaveURL(/\/create\/bom/)
    await second.close()
    // The BOM review tab picks the decision up from the shared ledger.
    await expect(page.getByTestId('counter-confirmed')).toContainText('1 of 14', { timeout: 10_000 })
    const panel = page.getByTestId('side-panel')
    await panel.getByRole('tab', { name: 'Similarity' }).click()
    await expect(panel.getByText('Confirmed surrogate').first()).toBeVisible()
    await expect(panel.getByTestId('similar-to')).toBeVisible()
    await expect(panel.getByTestId('audit-entry').first()).toContainText('Select as surrogate')
    await expect(page.getByTestId('counter-unresolved')).toContainText('2')
  })

  test('03b compare parts: viewers, computed constraints, requirements table links to trace', async ({ page }) => {
    await page.goto('/create/bom/03b-compare?line=BOML-0161')
    await expect(page.getByRole('heading', { name: /physical similarity/ })).toBeVisible()
    await expect(page.getByTestId('viewer-placeholder')).toHaveCount(2)
    await page.getByRole('button', { name: 'Alignment' }).click()
    await expect(page.getByTestId('viewer-placeholder')).toHaveCount(1)
    await expect(page.getByTestId('aligned-label')).toContainText(/Aligned · best fit from [3-5] constraints/)
    await expect(page.getByTestId('driving-reqs')).toContainText('REC-20001')
    await expect(page.getByTestId('open-trace')).toHaveAttribute('href', '/create/requirements/03c-trace?req=REC-20001')
    await expect(page.getByRole('button', { name: /Open PLM Record/ })).toBeDisabled()
    await page.getByRole('button', { name: 'Accept as Surrogate' }).click()
    await expect(page.getByText('Confirmed surrogate').first()).toBeVisible()
  })

  test('03d cost estimate: routing, six lines, trace, range rule, compare mode, confirm writes audit', async ({ page }) => {
    await page.goto('/create/bom/03d-cost?part=TC-404-C&line=BOML-0161')
    await expect(page.getByTestId('routing')).toContainText('Suggested · not yet confirmed')
    await expect(page.getByTestId('routing')).toContainText('68%')
    await expect(page.getByTestId('why-model').getByText('PLM', { exact: true })).toBeVisible()
    await expect(page.getByTestId('maturity')).toContainText('Have')
    await expect(page.getByTestId('cost-lines').locator('tr[data-line]')).toHaveCount(6)
    await expect(page.getByTestId('landed')).toHaveText('$168.00')
    await expect(page.getByTestId('range')).toContainText('±15%')
    await page.locator('tr[data-line="machining"]').click()
    await expect(page.getByTestId('trace')).toContainText('cycle time × machine rate ÷ yield')
    await expect(page.getByTestId('trace').locator('[data-input]').first()).toBeVisible()
    await expect(page.getByTestId('assumed-count')).toContainText('inputs assumed')
    await page.getByRole('button', { name: 'Open Features' }).first().click()
    await expect(page.getByRole('dialog', { name: /Detected features/ })).toBeVisible()
    await page.getByRole('button', { name: 'Close' }).last().click()
    await page.getByRole('button', { name: 'Confirm Model' }).click()
    await expect(page.getByTestId('routing')).toContainText('Confirmed')
    await expect(page.getByTestId('routing').getByTestId('audit-entry').first()).toContainText('Confirmed cost model')
    await expect(page.getByTestId('sourcing').locator('tr[data-supplier]')).toHaveCount(3)
    await expect(page.getByRole('button', { name: 'Set as Sourced' }).first()).toBeDisabled()
    await expect(page.getByTestId('fan-chart')).toBeVisible()
    // compare mode
    await page.getByRole('button', { name: /^Compare \(/ }).click()
    const cm = page.getByTestId('compare-mode')
    await cm.getByRole('checkbox').first().check({ force: true })
    await cm.getByRole('checkbox').nth(2).check({ force: true })
    await expect(page.getByRole('button', { name: /Compare \(2\)/ })).toBeVisible()
    await cm.getByRole('button', { name: 'Make Current' }).first().click()
    await expect(page.getByRole('button', { name: /Compare \(1\)/ })).toBeVisible()
  })

  test('04 composition: three buckets, counts, plan label, links into requirements', async ({ page }) => {
    await runSearch(page)
    await page.getByRole('button', { name: 'Retry' }).first().click()
    await expect(page.getByTestId('kpis')).toContainText('56 of 56 lines priced', { timeout: 10_000 })
    await page.getByRole('link', { name: /Open Program Composition/ }).click()
    await expect(page.getByTestId('count-new')).toHaveText('14')
    await expect(page.getByTestId('count-carryover')).toHaveText('41')
    await expect(page.getByTestId('count-uncertain')).toHaveText('1')
    await expect(page.getByTestId('composition-counts')).toContainText('244')
    await expect(page.getByTestId('composition-counts')).toContainText('98')
    await expect(page.getByRole('link', { name: 'Generate Test Plan' })).toHaveAttribute('href', '/create/requirements/05-mapping')
    await expect(page.getByRole('link', { name: 'Review Carryover' })).toHaveAttribute('href', '/create/requirements/06-carryover')
    await expect(page.getByRole('link', { name: 'Resolve Evidence' })).toBeVisible()
    await expect(page.getByTestId('sub-04-composition')).toContainText('14 new · 41 carryover · 1 uncertain')
  })

  for (const theme of THEMES) for (const density of DENSITIES) {
    test(`BOM review renders in ${theme} / ${density}`, async ({ page }) => {
      const errs = trackErrors(page)
      await setPrefs(page, { theme, density })
      await page.goto('/create/bom/03-review?line=BOML-0153&tab=similarity')
      await expect(page.getByTestId('bom-review')).toHaveAttribute('data-search', 'done')
      await expect(page.getByTestId('side-panel')).toBeVisible()
      await expect(page.locator('html')).toHaveAttribute('data-theme', theme)
      expect(await noHorizontalOverflow(page)).toBe(true)
      expect(errs).toEqual([])
    })
  }
})
