import { expect, test, type Page } from '@playwright/test'
import { DENSITIES, noHorizontalOverflow, setPrefs, THEMES, trackErrors } from './helpers'

const M = 'm=area:f10-face-14:18250.4&m=diameter:f10-edge-3:24.5'
const RESULTS = `/search/results?file=f10&modality=part-to-part&${M}`

async function useDev(page: Page, group: string, button: string) {
  await page.getByRole('button', { name: 'Dev toolbar' }).click()
  await page.getByRole('group', { name: group }).getByRole('button', { name: button }).click()
  await page.getByRole('button', { name: 'Dev toolbar' }).click()
}

test.describe('Search: flows', () => {
  test('Flow A: Files, filter, File Details, Search from file, Define, capture, Results, expand, Compare, Measurements', async ({ page }) => {
    const errs = trackErrors(page)
    await page.goto('/search/new')
    await expect(page.getByTestId('breadcrumbs')).toContainText('New Search')
    await expect(page.getByTestId('modality-cards').locator('button')).toHaveCount(4)
    await page.goto('/search/files?modality=part-to-part')
    await expect(page.getByTestId('breadcrumbs')).toContainText('Files')
    // filter by Release Status narrows the list and shows a pill
    const before = await page.getByTestId('result-count').innerText()
    await page.getByRole('button', { name: /^Release Status/ }).click()
    await page.getByRole('checkbox', { name: /^Released/ }).first().check()
    await expect(page.getByRole('toolbar', { name: 'Applied filters' })).toContainText('Release Status')
    expect(await page.getByTestId('result-count').innerText()).not.toBe(before)
    // search narrows, then open details
    await page.getByRole('textbox', { name: 'Search files' }).fill('k04-117*')
    await page.locator('tr[data-row-id]').first().click()
    await expect(page.getByTestId('side-panel')).toContainText('File details')
    await expect(page.getByTestId('side-panel').getByText('Builds a new search using this file as the reference.')).toBeVisible()
    await page.getByRole('tab', { name: 'PLM' }).click()
    await expect(page.getByRole('button', { name: 'Open in PLM' })).toBeDisabled()
    await page.getByRole('button', { name: 'Search from this file' }).click()
    // Define: capture an area measurement through the simulated picker
    await expect(page).toHaveURL(/\/search\/define\?/)
    await page.getByRole('tab', { name: /Measurements/ }).click()
    await page.getByRole('button', { name: 'New measurement' }).click()
    await page.getByRole('option').first().click()
    await page.getByRole('combobox', { name: 'Measurement type' }).selectOption({ label: 'Area (mm²)' })
    await page.getByRole('button', { name: 'Add measurement' }).click()
    await expect(page.getByTestId('measurement')).toHaveCount(1)
    await expect(page.getByTestId('meas-count')).toContainText('1/5')
    await page.getByRole('button', { name: 'Run Search' }).click()
    await expect(page.getByRole('heading', { name: /Found \d+ matching files/ })).toBeVisible()
    await expect(page.locator('tr[data-pinned]')).toContainText('Source Part')
    await expect(page.locator('tr[data-pinned]')).toContainText('0%')
    await expect(page.getByTestId('breadcrumbs')).toContainText('Results')
    const first = page.locator('tr[data-row-id]:not([data-pinned])').first()
    await first.getByRole('button', { name: 'Expand row' }).click()
    await expect(page.getByTestId('result-detail').getByRole('tab', { name: 'Measurements' })).toBeVisible()
    await first.getByRole('button', { name: 'Compare' }).click()
    await expect(page.getByTestId('breadcrumbs')).toContainText('Compare')
    await page.getByRole('tab', { name: /Measurements/ }).click()
    await expect(page.getByText('Search', { exact: true }).first()).toBeVisible()
    expect(errs).toEqual([])
  })

  test('New Search: card opens the upload popup, upload matches a fixture by name and continues to Define', async ({ page }) => {
    await page.goto('/search/new')
    await page.locator('[data-modality="part-to-part"]').click()
    await expect(page.getByRole('dialog')).toContainText('CATPart')
    await page.getByLabel('Choose a CAD file').setInputFiles({ name: 'k04-117-rs_brkt_mount.sldprt', mimeType: 'application/octet-stream', buffer: Buffer.from('x') })
    await expect(page.getByTestId('upload-match')).toContainText('K04-117-RS_BRKT_MOUNT.SLDPRT')
    await page.getByRole('button', { name: 'Continue to Define' }).click()
    await expect(page).toHaveURL(/\/search\/define\?.*src=new/)
    await expect(page.getByTestId('active-part')).toContainText('K04-117')
    // a wrong-kind file is refused inline
    await page.goto('/search/new')
    await page.locator('[data-modality="assembly-to-assembly"]').click()
    await page.getByLabel('Choose a CAD file').setInputFiles({ name: 'FrameBack_Outer_v8.CATPart', mimeType: 'application/octet-stream', buffer: Buffer.from('x') })
    await expect(page.getByRole('alert')).toContainText('needs an assembly')
  })

  test('Flow B: part number in another case with spacing finds the file, Released first, then Define and Results', async ({ page }) => {
    await page.goto('/search/files?q=7100490%200000%20ab&modality=part-to-part')
    const rows = page.locator('tr[data-row-id]')
    await expect(rows.first()).toContainText('7100490_0000_AB_ASM_RSB40_DEF.CATPart')
    await page.goto('/search/files?q=*rsb40*')
    expect(await page.locator('tr[data-row-id]').count()).toBeGreaterThan(5)
    await page.goto('/search/files?q=7100490')
    // Released (preferred) revisions come before the others
    const firstStatus = await page.locator('tr[data-row-id]').first().innerText()
    expect(firstStatus).toContain('7100490')
    await page.locator('tr[data-row-id]').first().click()
    await page.getByRole('button', { name: 'Search from this file' }).click()
    await page.getByRole('button', { name: 'Run Search' }).click()
    await expect(page.getByRole('heading', { name: /Found \d+ matching files/ })).toBeVisible()
  })

  test('assembly modalities: assembly to assembly, part to assembly, and part in assembly with a parent assembly column', async ({ page }) => {
    await page.goto('/search/results?file=f29&modality=assembly-to-assembly')
    await expect(page.locator('tr[data-pinned]')).toContainText('Assembly · 12 parts')
    await page.locator('tr[data-row-id]:not([data-pinned])').first().getByRole('button', { name: 'Expand row' }).click()
    await expect(page.getByTestId('result-detail').getByRole('tab', { name: /Contained Parts/ })).toBeVisible()
    await expect(page.getByTestId('result-detail').getByRole('tab', { name: /Related Revisions/ })).toBeVisible()
    await page.goto('/search/results?file=f19&modality=part-to-assembly')
    await expect(page.getByRole('heading', { name: /Found \d+ matching files/ })).toBeVisible()
    await page.goto('/search/results?file=f29&modality=part-in-assembly-to-part&part=n3')
    await expect(page.locator('th', { hasText: 'Parent assembly' })).toBeVisible()
    await page.locator('tr[data-row-id]:not([data-pinned])').first().getByRole('button', { name: 'Expand row' }).click()
    await expect(page.getByTestId('result-detail').getByRole('tab', { name: 'Sibling Parts' })).toBeVisible()
  })

  test('Define: tree selection sets the active part and implies the modality; measurement cap comes from config', async ({ page }) => {
    await page.goto('/search/define?file=f29&modality=part-to-part')
    await expect(page.getByTestId('active-part')).toContainText('Complete_Seat')
    await expect(page.getByText('Assembly → Assembly').or(page.getByText('Assembly to assembly'))).toBeVisible()
    await page.getByRole('treeitem').getByText('FrameBack_Outer').click()
    await expect(page.getByTestId('active-part')).toContainText('FrameBack_Outer')
    await expect(page.getByText('Part in assembly to part')).toBeVisible()
    await page.getByRole('treeitem').getByText('Headrest_Cover').click({ force: true })
    await expect(page.getByTestId('active-part')).toContainText('FrameBack_Outer')
    await page.getByRole('tab', { name: /Measurements/ }).click()
    for (let i = 0; i < 5; i++) {
      await page.getByRole('button', { name: 'New measurement' }).click()
      await page.getByRole('option').nth(i % 4).click()
      const sel = page.getByRole('combobox', { name: 'Measurement type' })
      await sel.selectOption({ index: 1 })
      await page.getByRole('button', { name: 'Add measurement' }).click()
    }
    await expect(page.getByTestId('meas-count')).toContainText('5/5')
    await expect(page.getByRole('button', { name: /Maximum of 5 measurements/ })).toBeDisabled()
  })

  test('decision actions: none without a workflow context; with one, apply, audit, return, visible from a second page', async ({ page, context }) => {
    await page.goto(RESULTS)
    await expect(page.getByRole('button', { name: 'Select as surrogate' })).toHaveCount(0)
    const ret = encodeURIComponent('/search/new')
    await page.goto(`${RESULTS}&ctx=${encodeURIComponent('bom-review:BOML-0152')}&ret=${ret}`)
    await expect(page.getByRole('button', { name: 'Select as surrogate' }).first()).toBeVisible()
    // Search on opens a new tab carrying the context
    const [popup] = await Promise.all([context.waitForEvent('page'), page.locator('tr[data-row-id]:not([data-pinned])').first().getByRole('link', { name: /Search on/ }).click()])
    await popup.waitForLoadState()
    expect(popup.url()).toMatch(/\/search\/define\?.*ctx=bom-review/)
    await popup.getByRole('button', { name: 'Run Search' }).click()
    await expect(popup.getByRole('button', { name: 'Select as surrogate' }).first()).toBeVisible()
    await popup.getByRole('button', { name: 'Select as surrogate' }).first().click()
    await expect(popup).toHaveURL(/\/search\/new/)
    await expect(popup.getByText(/Select as surrogate:/)).toBeVisible()
    // the original page sees the audit entry through the shared ledger
    await page.reload()
    await page.getByRole('button', { name: 'Notifications' }).click()
    await expect(page.getByTestId('audit-entry').first()).toContainText('Select as surrogate')
    await expect(page.getByTestId('audit-entry').first()).toContainText('Aaron Keller')
  })

  test('Review required rows confirm with an audit entry and a toast (workflow context only)', async ({ page }) => {
    await page.goto(RESULTS)
    await expect(page.getByRole('button', { name: 'Confirm' })).toHaveCount(0)
    await page.goto(`${RESULTS}&ctx=${encodeURIComponent('bom-review:BOML-0152')}&ret=${encodeURIComponent('/search/new')}`)
    await page.getByRole('button', { name: 'Confirm' }).first().click()
    await expect(page.getByRole('status').getByText(/Confirmed:/)).toBeVisible()
    await page.getByRole('button', { name: 'Notifications' }).click()
    await expect(page.getByTestId('audit-entry').first()).toContainText('Confirmed')
  })

  test('Results: manual measurement state, no Exact wording, duplicate chips, disabled PLM link', async ({ page }) => {
    await page.goto(RESULTS)
    await expect(page.locator('body')).not.toContainText(/exact/i)
    await expect(page.getByText('Geometric duplicate').first()).toBeVisible()
    await expect(page.getByText('Manual measurement required').first()).toBeVisible()
    await expect(page.getByRole('button', { name: 'Open in PLM' }).first()).toBeDisabled()
    await page.goto('/search/results?file=f07&modality=part-to-part&m=area:f07-face-10:9000')
    await expect(page.getByText('Duplicate file').first()).toBeVisible()
    await expect(page.getByText('No match').first()).toBeVisible()
    await expect(page.getByText('Search failed').first()).toBeVisible()
    await expect(page.locator('body')).not.toContainText(/exact/i)
    // measurement tab: manual state with call to action
    await page.goto(RESULTS)
    const row = page.locator('tr[data-row-id]:not([data-pinned])', { hasText: 'Manual measurement required' }).first()
    await row.getByRole('button', { name: 'Expand row' }).click()
    await page.getByTestId('result-detail').getByRole('tab', { name: 'Measurements' }).click()
    await expect(page.getByTestId('measurements-table')).toContainText('Manual measurement required')
    await expect(page.getByTestId('measurements-table').getByRole('button', { name: 'Measure in Compare' })).toBeVisible()
  })

  test('Results filters: similarity, confidence level and data type narrow the rows; Save Search toasts', async ({ page }) => {
    await page.goto(RESULTS)
    const count = page.getByTestId('result-count')
    const total = await count.innerText()
    await page.getByRole('button', { name: /^Data type/ }).click()
    await page.getByRole('checkbox', { name: /^Surrogate/ }).check()
    expect(await count.innerText()).not.toBe(total)
    await page.getByRole('button', { name: 'Clear all' }).first().click()
    await page.getByRole('button', { name: /^Confidence/ }).click()
    await page.getByRole('group', { name: 'Confidence' }).getByRole('button', { name: /^High/ }).click()
    expect(await count.innerText()).not.toBe(total)
    await page.getByRole('button', { name: 'Save Search' }).click()
    await expect(page.getByRole('status').getByText(/Search saved/)).toBeVisible()
  })

  test('Compare: alignment constraints, DOF counter, warning, overlay reached only through Align and compute overlap', async ({ page }) => {
    await page.goto(`/search/compare?query=f10&result=f12&file=f10&modality=part-to-part&${M}`)
    await expect(page.getByRole('tab', { name: 'Overlay' })).toHaveCount(0)
    await page.getByRole('button', { name: 'Alignment' }).click()
    await expect(page.getByTestId('dof')).toContainText('6 degrees of freedom remaining')
    await page.getByRole('combobox', { name: 'Query face' }).selectOption({ index: 1 })
    await page.getByRole('combobox', { name: 'Result face' }).selectOption({ index: 1 })
    await page.getByRole('button', { name: 'Add constraint' }).click()
    await expect(page.getByTestId('constraint')).toHaveCount(1)
    await expect(page.getByTestId('dof')).not.toContainText('6 degrees')
    await expect(page.getByRole('status').filter({ hasText: 'Under-constrained' })).toBeVisible()
    await page.getByRole('button', { name: 'Align and compute overlap' }).click()
    await expect(page.getByTestId('overlay-stats')).toBeVisible()
    await expect(page.getByTestId('aligned-by')).toHaveText('1 constraint')
    await expect(page.getByText('Query only').first()).toBeVisible()
    await expect(page.getByTestId('volume-match')).toContainText('%')
    await page.getByRole('button', { name: 'Back to Alignment' }).click()
    await page.getByRole('button', { name: 'Remove Coplanar constraint' }).or(page.getByRole('button', { name: /^Remove .* constraint/ })).first().click()
    await expect(page.getByTestId('dof')).toContainText('6 degrees')
  })

  test('Compare PLM tab highlights matching values', async ({ page }) => {
    await page.goto(`/search/compare?query=f10&result=f12&file=f10&modality=part-to-part`)
    await page.getByRole('tab', { name: 'PLM' }).click()
    await expect(page.getByTestId('compare-plm').locator('td[data-match="true"]').first()).toBeVisible()
  })

  test('schema switch changes Files sidebar groups, columns and detail fields with no reload', async ({ page }) => {
    await page.goto('/search/files?modality=part-to-part')
    await expect(page.getByTestId('filter-sidebar').getByRole('button', { name: /^Customer Group/ })).toBeVisible()
    await page.locator('tr[data-row-id]').first().click()
    await page.getByRole('tab', { name: 'PLM' }).click()
    await expect(page.getByTestId('side-panel').getByText('Release Status')).toBeVisible()
    await useDev(page, 'Schema', 'Company B')
    await expect(page.getByTestId('filter-sidebar').getByRole('button', { name: /^Customer Group/ })).toHaveCount(0)
    await expect(page.getByTestId('filter-sidebar').getByRole('button', { name: /^Vehicle line/ })).toBeVisible()
    await expect(page.getByTestId('filter-sidebar').getByRole('button', { name: /^Supplier lead time/ })).toBeVisible()
    await page.locator('tr[data-row-id]').first().click()
    await page.getByRole('tab', { name: 'PLM' }).click()
    await expect(page.getByTestId('side-panel').getByText('Maturity')).toBeVisible()
    // columns that appear only when their filter is applied: at most three
    const vl = page.getByTestId('filter-sidebar').getByRole('button', { name: /^Vehicle line/ })
    if ((await vl.getAttribute('aria-expanded')) === 'false') await vl.click()
    await page.getByRole('checkbox', { name: /^Atlas EV/ }).check()
    await expect(page.locator('th', { hasText: 'Vehicle line' })).toBeVisible()
  })

  test('Files: Released Date has a real date-range control; gallery and sort work; empty state copy', async ({ page }) => {
    await page.goto('/search/files')
    const sidebar = page.getByTestId('filter-sidebar')
    await sidebar.getByRole('button', { name: /^Released Date/ }).click()
    const total = await page.getByTestId('result-count').innerText()
    await sidebar.getByLabel('Custom range').check()
    await sidebar.getByLabel('From date').fill('2026-04-01')
    await sidebar.getByLabel('To date').fill('2026-05-31')
    expect(await page.getByTestId('result-count').innerText()).not.toBe(total)
    await expect(page.locator('th', { hasText: 'Released Date' })).toBeVisible()
    await page.getByRole('button', { name: 'Clear all' }).last().click()
    await page.getByRole('combobox', { name: 'Sort by' }).selectOption({ label: 'File name' })
    await page.getByRole('button', { name: 'Gallery view' }).click()
    await expect(page.locator('button[class*="card"]').first()).toBeVisible()
    await page.getByRole('textbox', { name: 'Search files' }).fill('zzzz-no-such-file')
    await expect(page.getByText('No files match the current filters and search.')).toBeVisible()
  })

  test('PLM links stay disabled and Stub outlines mark the simulated pieces', async ({ page }) => {
    await page.goto(`${RESULTS}&showStubs=1`)
    await page.getByRole('button', { name: 'Dev toolbar' }).click()
    await page.getByRole('group', { name: 'Show stubs' }).getByRole('button', { name: 'Outlined' }).click()
    await expect(page.locator('[data-stub="matching-engine"]').first()).toBeVisible()
    await expect(page.locator('[data-stub="plm-connectors"]').first()).toBeVisible()
  })
})

test.describe('Search: themes and densities on Results', () => {
  for (const theme of THEMES) for (const density of DENSITIES) {
    test(`Results renders in ${theme} / ${density}`, async ({ page }) => {
      const errs = trackErrors(page)
      await setPrefs(page, { theme, density })
      await page.goto(RESULTS)
      await expect(page.getByRole('heading', { name: /Found \d+ matching files/ })).toBeVisible()
      await expect(page.locator('html')).toHaveAttribute('data-theme', theme)
      expect(await noHorizontalOverflow(page)).toBe(true)
      expect(errs).toEqual([])
    })
  }
})
